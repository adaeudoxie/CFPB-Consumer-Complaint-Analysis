"""Profile the RAW dataset and write outputs/data_inspection_report.md.

Every figure in the report is computed here, so the report can be regenerated at any time:
    python src/data_inspection.py [--input PATH]
"""
from __future__ import annotations
import argparse
from datetime import date
import pandas as pd
import config as C
from data_cleaning import load_raw


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(f"{v:,}" if isinstance(v, (int,)) and not isinstance(v, bool) else str(v) for v in r) + " |")
    return "\n".join(lines)


def vc(s: pd.Series, n=None, label="Value") -> str:
    t = s.value_counts(dropna=False)
    if n:
        t = t.head(n)
    df = pd.DataFrame({label: t.index.astype(object).where(t.index.notna(), "(blank)"),
                       "Count": t.values.astype(int),
                       "% of rows": (t.values / len(s) * 100).round(2)})
    df["Count"] = df["Count"].map(lambda x: f"{x:,}")
    return md_table(df)


TEXT_COLS = [c for c in C.RAW_COLUMNS if c not in ('Complaint ID', 'Date submitted', 'Date received')]


def build(df: pd.DataFrame, source: str) -> str:
    n = len(df)
    ds, dr = pd.to_datetime(df["Date submitted"]), pd.to_datetime(df["Date received"])
    fi = (dr - ds).dt.days
    months = ds.dt.to_period("M")
    full_range = pd.period_range(months.min(), months.max(), freq="M")
    blank_timely = df["Timely response?"].isna()
    in_prog = df["Company response to consumer"] == "In progress"

    prof = pd.DataFrame({
        "Column": df.columns,
        "Type": [str(t) for t in df.dtypes],
        "Non-null": [f"{df[c].notna().sum():,}" for c in df.columns],
        "Blank": [f"{df[c].isna().sum():,}" for c in df.columns],
        "% blank": [round(df[c].isna().mean() * 100, 2) for c in df.columns],
        "Distinct": [f"{df[c].nunique():,}" for c in df.columns],
    })
    yearly = ds.dt.year.value_counts().sort_index()
    attrs = [c for c in df.columns if c != "Complaint ID"]
    grp = df[df.duplicated(subset=attrs, keep=False)]
    grp_rows, n_groups = len(grp), grp.groupby(attrs, dropna=False).ngroups
    span = grp.groupby(attrs, dropna=False)["Complaint ID"].agg(lambda s: s.max() - s.min())
    row_span = grp.groupby(attrs, dropna=False)["Complaint ID"].transform(lambda s: s.max() - s.min())
    near_ids = grp.loc[row_span <= 5, "Complaint ID"]
    out = [
        "# Data Inspection Report (raw data)",
        f"_Generated by `src/data_inspection.py` on {date.today()} from `{source}`. The raw file is read only._",
        "",
        "## 1. Structure",
        f"- Worksheet: `{C.SHEET}`",
        f"- Rows: **{n:,}** (expected {C.EXPECTED_ROWS:,}) · Columns: **{df.shape[1]}** (expected {C.EXPECTED_COLS})",
        "",
        md_table(prof),
        "",
        "## 2. Keys and duplicates",
        f"- Distinct Complaint IDs: **{df['Complaint ID'].nunique():,}**. Duplicate IDs: **{df['Complaint ID'].duplicated().sum():,}**",
        f"- Fully duplicated rows: **{df.duplicated().sum():,}**",
        f"- Rows that repeat an earlier row on all 11 non-ID attributes: **{df.drop(columns='Complaint ID').duplicated().sum():,}**, "
        f"forming **{grp_rows:,} rows in {n_groups:,} same-attribute groups**. Only "
        f"{(df.drop(columns='Complaint ID').duplicated() & (df['Company response to consumer']=='In progress')).sum()} of the repeats are 'In progress', "
        "so the count matching the 1,494 In-progress records is a coincidence.",
        f"  - In {(span <= 5).sum():,} groups ({(df['Complaint ID'].isin(near_ids)).sum():,} rows), the IDs are within 5 of each other. These are "
        "**possible repeat submissions** of the same complaint. The rest are spread across hundreds or thousands of IDs and are most likely separate "
        "complaints that share common attributes.",
        "  - **Decision:** all records are kept, because distinct Complaint IDs mean distinct complaints. They are flagged in the cleaned data "
        "(`DQ Same-Attribute Group`, `DQ Possible Repeat Submission`) so the effect on any KPI can be measured.",
        "",
        "## 3. Dates",
        f"- Date submitted (CFPB received): {ds.min().date()} to {ds.max().date()}",
        f"- Date received (CFPB sent to company): {dr.min().date()} to {dr.max().date()}",
        f"- Records where Date received is before Date submitted: **{(fi < 0).sum():,}**",
        f"- Months covered: **{months.nunique()}** of {len(full_range)} in range. Missing months: **{len(set(full_range) - set(months.unique()))}**",
        f"- Last month ({months.max()}) ends on {ds.max().date()}, so it is a **partial month**. "
        f"{ds.max().year} is a **partial year** (Jan–{ds.max().strftime('%b')}), and so is {ds.min().year} ({ds.min().strftime('%b')}–Dec).",
        f"- First month ({months.min()}) starts on {ds.min().date()}, the first day of the month, so it appears complete within the "
        "supplied extract. The year it starts, however, is only partially covered.",
        "",
        "### Annual record counts (by Date submitted)",
        md_table(pd.DataFrame({"Year": yearly.index.astype(str), "Complaints": [f"{v:,}" for v in yearly.values]})),
        "",
        "## 4. CFPB forwarding interval (Date received − Date submitted, days)",
        "This interval measures how long the CFPB took to send a complaint to the company. It is **not** the company's response or resolution time.",
        "",
        md_table(pd.DataFrame({
            "Statistic": ["Mean", "Median", "Std dev", "Min", "P90", "P95", "P99", "Max", "> 7 days", "> 30 days"],
            "Value": [round(fi.mean(), 2), fi.median(), round(fi.std(), 2), fi.min(), fi.quantile(.9), fi.quantile(.95),
                      fi.quantile(.99), fi.max(), f"{(fi > 7).sum():,}", f"{(fi > 30).sum():,}"]})),
        "",
        "## 5. Categorical distributions",
        "### Submitted via", vc(df["Submitted via"], label="Channel"), "",
        "### Product", vc(df["Product"], label="Product"), "",
        "### Company response to consumer", vc(df["Company response to consumer"], label="Response"), "",
        "### Company public response", vc(df["Company public response"], label="Public response"), "",
        "### Timely response?", vc(df["Timely response?"], label="Timely"), "",
        f"- States: {df['State'].nunique()} distinct codes (50 states + DC). Invalid codes: "
        f"{(~df['State'].str.fullmatch(r'[A-Z]{2}')).sum()}",
        "",
        "## 6. Blank-value investigation",
        f"- **Timely response?** blanks: {blank_timely.sum():,}. Of these, {(blank_timely & in_prog).sum():,} are 'In progress'. "
        f"'In progress' complaints with a non-blank Timely value: {(in_prog & ~blank_timely).sum():,}. "
        "**The blanks and 'In progress' are the same records**, so the blanks are pending, not 'No'.",
        f"  - Submission dates of these records: {ds[blank_timely].min().date()} to {ds[blank_timely].max().date()}.",
        f"- **Sub-issue** blanks: {df['Sub-issue'].isna().sum():,}. The data dictionary says not every issue has sub-issues. By product:",
        md_table(df[df["Sub-issue"].isna()]["Product"].value_counts().rename_axis("Product").reset_index(name="Blank sub-issues")
                 .assign(**{"Blank sub-issues": lambda x: x["Blank sub-issues"].map(lambda v: f"{v:,}")})),
        f"- **Company public response** blanks: {df['Company public response'].isna().sum():,}. By year:",
        md_table(ds[df["Company public response"].isna()].dt.year.value_counts().sort_index()
                 .rename_axis("Year").reset_index(name="Blank public responses").astype(str)),
        f"- **Sub-product** blanks: {df['Sub-product'].isna().sum():,}. All are in: "
        f"{', '.join(df[df['Sub-product'].isna()]['Product'].unique())}.",
        "",
        "## 7. Consistency checks",
        f"- Leading or trailing whitespace in text columns: "
        f"{sum((df[c].dropna().astype(str) != df[c].dropna().astype(str).str.strip()).sum() for c in TEXT_COLS)}",
        f"- Case-variant duplicates (e.g. 'Mortgage' vs 'mortgage'): "
        f"{sum(df[c].dropna().nunique() - df[c].dropna().str.lower().nunique() for c in ['Product','Sub-product','Issue','Sub-issue','Submitted via'])}",
        f"- 'Closed' (no further detail) responses: {(df['Company response to consumer']=='Closed').sum()}. "
        f"Timely values for these: {df.loc[df['Company response to consumer']=='Closed','Timely response?'].value_counts().to_dict()}",
        f"- Issues that appear under more than one Product: {(df.groupby('Issue')['Product'].nunique() > 1).sum()} "
        "(e.g. credit-reporting issues are reported under card, mortgage and bank-account products). "
        "This follows the CFPB form's design and is not a data error.",
    ]
    return "\n".join(out) + "\n"


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--input", default=str(C.RAW_FILE))
    a = p.parse_args(argv)
    df = load_raw(a.input)
    C.OUTPUTS_DIR.mkdir(exist_ok=True)
    path = C.OUTPUTS_DIR / "data_inspection_report.md"
    path.write_text(build(df, "01_Raw_Data/Consumer_Complaints.xlsx"), encoding="utf-8")
    print(f"Wrote {path}")


if __name__ == "__main__":
    main()
