"""Compare every Python KPI table with its independently written SQL equivalent.

    python src/cross_check.py

Writes outputs/kpi_crosscheck.md; exits non-zero if any KPI differs.
"""
from __future__ import annotations
import sys
from datetime import date
import pandas as pd
import config as C

OUT = C.OUTPUTS_DIR / "kpi_outputs"


def compare(py: pd.DataFrame, sq: pd.DataFrame) -> tuple[bool, str]:
    if list(py.columns) != list(sq.columns):
        return False, f"columns differ: {list(py.columns)} vs {list(sq.columns)}"
    if len(py) != len(sq):
        return False, f"row count {len(py)} vs {len(sq)}"
    keys = [c for c in py.columns if not pd.api.types.is_numeric_dtype(py[c])]
    if keys:
        py, sq = py.sort_values(keys, ignore_index=True), sq.sort_values(keys, ignore_index=True)
    diffs = []
    for c in py.columns:
        a, b = py[c], sq[c]
        if pd.api.types.is_numeric_dtype(a) and pd.api.types.is_numeric_dtype(b):
            bad = ~((a - b).abs().le(0.011) | (a.isna() & b.isna()))
        else:
            bad = a.astype(str) != b.astype(str)
        if bad.any():
            diffs.append(f"{c}: {int(bad.sum())} cells")
    return (not diffs), ("identical" if not diffs else "; ".join(diffs))


def main():
    rows = []
    for py_file in sorted(OUT.glob("PY_*.csv")):
        name = py_file.stem[3:]
        sq_file = OUT / f"SQL_{name}.csv"
        if not sq_file.exists():
            rows.append((name, "FAIL", "no SQL equivalent")); continue
        ok, msg = compare(pd.read_csv(py_file), pd.read_csv(sq_file))
        rows.append((name, "PASS" if ok else "FAIL", f"{len(pd.read_csv(py_file))} rows, {msg}"))
    passed = sum(r[1] == "PASS" for r in rows)
    md = ["# KPI Cross-Check: Python vs SQL", f"_Generated by `src/cross_check.py` on {date.today()}._", "",
          "Each KPI was calculated twice, in pandas (`src/analysis.py`) and in SQLite (`sql/kpi_calculations.sql`), "
          "using code written independently. A KPI passes only if every row and value matches (tolerance ±0.01 for rounded percentages).", "",
          f"**{passed} of {len(rows)} KPI tables match.**", "", "| KPI table | Result | Detail |", "|---|---|---|"]
    md += [f"| {n} | {'✅' if r == 'PASS' else '❌'} {r} | {m} |" for n, r, m in rows]
    (C.OUTPUTS_DIR / "kpi_crosscheck.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(f"{r:4} {n}: {m}" for n, r, m in rows)); print(f"{passed}/{len(rows)} match")
    sys.exit(0 if passed == len(rows) else 1)


if __name__ == "__main__":
    main()
